"""Simulated live source station.

Runs a TCP server. Each connected upstream pulls a real libx264 encoded
Annex-B stream generated by ffmpeg (moving test pattern with a frame counter
burned in). With --supervise the process forks a supervisor that restarts the
ffmpeg pipeline on demand, which is how the "short source outage" scenario is
exercised without killing the source endpoint itself.

Control API:
  GET  /stats            upstream connection count, state
  POST /control/die      kill the current ffmpeg pipeline (supervisor restarts it)
  POST /control/stop     full shutdown (supervisor exits as well)
"""
import argparse
import asyncio
import json
import os
import signal
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import AccessUnitFramer

FFMPEG = str(Path(__file__).parent / "bin" / "ffmpeg")


class SourceServer:
    def __init__(self, host: str, port: int, label: str):
        self.host = host
        self.port = port
        self.label = label
        self.connections = 0
        self.bytes_sent = 0
        self.generators = set()
        self.gen_started_at = 0.0
        self.restart_count = 0
        self.stopping = asyncio.Event()
        self._server = None
        self._watchers = set()

    @property
    def generator_alive(self) -> bool:
        return any(p.returncode is None for p in self.generators)

    def _box_color(self) -> str:
        # Distinct marker color per region label (deterministic).
        palette = {"EAST-SRC": "0x38d39f", "NORTH-SRC": "0x5aa7ff"}
        return palette.get(self.label, "0xf5a623")

    # ---- ffmpeg pipeline supervision -------------------------------------
    async def _pump(self, writer: asyncio.StreamWriter):
        """Spawn one ffmpeg per connection and forward its stdout."""
        # Encode fixed-duration chunks, then release them on the wall clock.
        # Writing a whole chunk at once would just fill the TCP send buffer,
        # so the paced send below is what actually bounds the upstream rate.
        # dump_extra re-emits SPS/PPS at every keyframe, keeping each chunk
        # independently decodable.
        chunk_secs = 1
        fps = 15
        cmd = [
            FFMPEG, "-hide_banner", "-loglevel", "error",
            "-f", "lavfi", "-i",
            f"testsrc2=size=640x360:rate={fps}",
            # Static builds may lack libfreetype, so avoid drawtext; drawbox
            # is always available and marks the region on every frame.
            "-vf", f"drawbox=x=8:y=8:w=180:h=36:color=black@0.6:t=fill,"
                   f"drawbox=x=16:y=16:w=120:h=20:color={self._box_color()}:t=fill",
            "-c:v", "libx264", "-preset", "veryfast", "-tune", "zerolatency",
            "-g", str(fps), "-keyint_min", str(fps), "-sc_threshold", "0",
            "-pix_fmt", "yuv420p", "-bsf:v", "dump_extra",
            "-t", str(chunk_secs), "-f", "h264", "pipe:1",
        ]
        tick = 1.0 / fps
        try:
            while not writer.is_closing():
                proc = await asyncio.create_subprocess_exec(
                    *cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
                self.generators.add(proc)
                self.gen_started_at = time.time()
                encoded = await proc.stdout.read()
                await proc.wait()
                self.generators.discard(proc)
                # Re-frame into access units and send one picture per tick.
                framer = AccessUnitFramer()
                units = [au for _, _, au in framer.push(encoded)]
                deadline = time.time()
                for au in units:
                    writer.write(au)
                    await writer.drain()
                    self.bytes_sent += len(au)
                    deadline += tick
                    wait = deadline - time.time()
                    if wait > 0:
                        await asyncio.sleep(wait)
        except (ConnectionResetError, BrokenPipeError):
            pass
        finally:
            for p in list(self.generators):
                if p.returncode is None:
                    p.kill()
                    await p.wait()
                self.generators.discard(p)

    async def handle_client(self, reader, writer):
        self.connections += 1
        peer = writer.get_extra_info("peername")
        print(f"[source] upstream connected from {peer}, total={self.connections}",
              flush=True)
        pump = asyncio.create_task(self._pump(writer))
        try:
            await reader.read()  # hold until the relay disconnects
        finally:
            pump.cancel()
            try:
                await pump
            except (asyncio.CancelledError, Exception):
                pass
            self.connections -= 1
            writer.close()
            try:
                await writer.wait_closed()
            except Exception:
                pass
            print(f"[source] upstream closed, total={self.connections}", flush=True)

    # ---- control HTTP -----------------------------------------------------
    async def _http_handler(self, reader, writer):
        line = await reader.readline()
        if not line:
            writer.close()
            return
        try:
            method, path, _ = line.decode().split(" ", 2)
        except ValueError:
            writer.close()
            return
        length = 0
        while True:
            h = await reader.readline()
            if h in (b"\r\n", b"\n", b""):
                break
            if h.lower().startswith(b"content-length:"):
                length = int(h.split(b":", 1)[1].strip())
        if length:
            await reader.readexactly(length)
        if method == "GET" and path == "/stats":
            body = json.dumps({
                "upstream_connections": self.connections,
                "generator_alive": self.generator_alive,
                "bytes_sent": self.bytes_sent,
                "restart_count": self.restart_count,
            }).encode()
            writer.write(b"HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
                         b"Content-Length: " + str(len(body)).encode() +
                         b"\r\nConnection: close\r\n\r\n" + body)
        elif method == "POST" and path == "/control/die":
            if os.environ.get("RELAY_SUPERVISED") == "1":
                # Exit so the supervisor restarts the whole endpoint: this is
                # the realistic "short source outage" simulation.
                writer.write(b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\n{}")
                await writer.drain()
                writer.close()
                os._exit(42)
            for proc in list(self.generators):
                if proc.returncode is None:
                    proc.kill()
            self.restart_count += 1
            writer.write(b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\n{}")
        elif method == "POST" and path == "/control/stop":
            self.stopping.set()
            writer.write(b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\n{}")
        else:
            writer.write(b"HTTP/1.1 404 NF\r\nContent-Length: 0\r\n\r\n")
        await writer.drain()
        writer.close()

    async def serve(self):
        self._server = await asyncio.start_server(self.handle_client, self.host, self.port)
        await asyncio.start_server(self._http_handler, self.host, self.port + 1)
        print(f"[source] stream on {self.host}:{self.port}, control on "
              f"{self.host}:{self.port + 1}", flush=True)
        await self.stopping.wait()
        self._server.close()
        await self._server.wait_closed()


async def run_server(host, port, label):
    srv = SourceServer(host, port, label)
    await srv.serve()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, required=True)
    ap.add_argument("--label", default="LIVE")
    ap.add_argument("--supervise", action="store_true",
                    help="fork a supervisor that restarts this server on failure")
    args = ap.parse_args()

    if not args.supervise:
        asyncio.run(run_server(args.host, args.port, args.label))
        return

    # Supervisor mode: restart the child unless an explicit stop was requested.
    state = {"stopping": False, "child": None}

    def _term(*_):
        state["stopping"] = True
        child = state["child"]
        if child and child.poll() is None:
            child.terminate()

    signal.signal(signal.SIGTERM, _term)
    signal.signal(signal.SIGINT, _term)
    restarts = 0
    while not state["stopping"]:
        env = dict(os.environ, RELAY_SUPERVISED="1")
        child = subprocess.Popen([sys.executable, __file__,
                                  "--host", args.host, "--port", str(args.port),
                                  "--label", args.label], env=env)
        state["child"] = child
        rc = child.wait()
        if state["stopping"]:
            break
        restarts += 1
        print(f"[source-supervisor] child exited rc={rc}, restart {restarts}",
              flush=True)
        time.sleep(0.5)
    print("[source-supervisor] stopped", flush=True)


if __name__ == "__main__":
    main()
